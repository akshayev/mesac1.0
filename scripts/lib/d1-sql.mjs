// SQL text for the one-off scripts that feed D1 through `wrangler d1 execute --file` (which cannot bind
// parameters). Every value goes through sqlLiteral(); emails are additionally limited by strictEmail() to
// characters that cannot contain a quote. Tested in scripts/tests/d1-tools.test.mjs.

import { randomBytes } from "node:crypto";
import { strictEmail } from "./validate.mjs";

export const newId = () => randomBytes(16).toString("hex");

/** A value as a SQLite literal: NULL, a finite number, or a single-quoted string with quotes doubled. */
export function sqlLiteral(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error("not a finite number");
    return String(v);
  }
  return `'${String(v).replace(/\0/g, "").replace(/'/g, "''")}'`;
}

const insert = (table, row) => {
  const cols = Object.keys(row);
  return `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${cols.map((c) => sqlLiteral(row[c])).join(", ")});`;
};

/**
 * One-time import of the Sheet data into D1. `data` has the snapshot shapes (team, achievements,
 * placements, alumni arrays; settings object). Alumni in a snapshot have already passed the consent check;
 * they are marked consent_source = 'sheet_import'.
 */
export function importSql(data, { now = new Date().toISOString(), id = newId } = {}) {
  const meta = (item, i) => ({
    visible: 1,
    sort_order: Number.isFinite(item.order) ? item.order : i + 1,
    created_at: now,
    updated_at: now,
    updated_by: "sheet-import",
  });
  const lines = [
    "-- Generated by scripts/import-sheet-to-d1.mjs. Contains personal data: do not commit; delete after use.",
  ];
  (data.team ?? []).forEach((p, i) =>
    lines.push(
      insert("team_members", {
        id: id(),
        name: p.name,
        role: p.role ?? "",
        group_name: p.group || "Team",
        photo: p.photo ?? "",
        linkedin: p.linkedin ?? "",
        email: p.email ?? "",
        ...meta(p, i),
      }),
    ),
  );
  (data.achievements ?? []).forEach((a, i) =>
    lines.push(
      insert("achievements", {
        id: id(),
        title: a.title,
        date: a.date ?? null,
        category: a.category ?? "",
        description: a.description ?? "",
        image: a.image ?? "",
        link: a.link ?? "",
        ...meta(a, i),
      }),
    ),
  );
  (data.placements ?? []).forEach((p, i) =>
    lines.push(
      insert("placements", {
        id: id(),
        name: p.name,
        company: p.company,
        role: p.role ?? "",
        batch: p.batch ?? "",
        photo: p.photo ?? "",
        linkedin: p.linkedin ?? "",
        ...meta(p, i),
      }),
    ),
  );
  (data.alumni ?? []).forEach((a, i) =>
    lines.push(
      insert("alumni", {
        id: id(),
        name: a.name,
        batch: a.batch ?? "",
        department: a.department ?? "",
        current_role: a.currentRole ?? "",
        company: a.company ?? "",
        location: a.location ?? "",
        photo: a.photo ?? "",
        linkedin: a.linkedin ?? "",
        email: a.email ?? "",
        phone: a.phone ?? "",
        help_with: (a.helpWith ?? []).join("; "),
        consent: 1,
        consent_at: now,
        consent_source: "sheet_import",
        ...meta(a, i),
      }),
    ),
  );
  for (const [key, value] of Object.entries(data.settings ?? {})) {
    if (!value) continue;
    lines.push(
      `INSERT INTO settings (key, value, updated_at, updated_by) VALUES (${sqlLiteral(key)}, ${sqlLiteral(value)}, ${sqlLiteral(now)}, 'sheet-import') ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at, updated_by = excluded.updated_by;`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * "a@x.org, b@y.org" -> validated, lowercased, de-duplicated emails. Throws (without repeating the value)
 * on any entry that is not a plain email address.
 */
export function parseEmailList(raw, { max = 20 } = {}) {
  const parts = String(raw ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const out = [];
  parts.forEach((p, i) => {
    const email = strictEmail(p);
    if (!email) throw new Error(`entry ${i + 1} is not a valid email address`);
    if (!out.includes(email)) out.push(email);
  });
  if (out.length > max) throw new Error(`at most ${max} emails`);
  return out;
}

/**
 * First admins: inserted in ONE statement, and only while the admins table is empty. Once anyone is an
 * admin, this does nothing, so an admin removed in the dashboard is never re-added by a later deploy.
 */
export function bootstrapSql(emails, { now = new Date().toISOString(), id = newId } = {}) {
  if (!emails.length) return "";
  const rows = emails
    .map((e) => {
      if (strictEmail(e) !== e) throw new Error("emails must come from parseEmailList");
      return `(${[id(), e, "admin", 1, now, now, "bootstrap"].map(sqlLiteral).join(", ")})`;
    })
    .join(", ");
  return `INSERT INTO admins (id, email, role, active, created_at, updated_at, updated_by) SELECT column1, column2, column3, column4, column5, column6, column7 FROM (VALUES ${rows}) WHERE NOT EXISTS (SELECT 1 FROM admins);\n`;
}

/** Local development only: add (or re-activate) one admin. */
export function addAdminSql(email, role, { now = new Date().toISOString(), id = newId } = {}) {
  const e = strictEmail(email);
  if (!e) throw new Error("not a valid email address");
  if (role !== "admin" && role !== "editor") throw new Error("role must be admin or editor");
  return `INSERT INTO admins (id, email, role, active, created_at, updated_at, updated_by) VALUES (${[id(), e, role, 1, now, now, "local-dev"].map(sqlLiteral).join(", ")}) ON CONFLICT(email) DO UPDATE SET role = excluded.role, active = 1, updated_at = excluded.updated_at;\n`;
}
