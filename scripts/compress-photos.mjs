#!/usr/bin/env node
// Shrinks photos for the website: max 600 px on the long side, WebP, quality 78.
//
//   node scripts/compress-photos.mjs <source-folder> [output-folder]
//   (output defaults to public/people)
//
// - File names become lowercase with hyphens: "Jane Doe (2).JPG" -> "jane-doe-2.webp"
// - EXIF rotation is applied (phone photos stay upright) and metadata (GPS etc.) is dropped.
// - Writes data/people-photos.md with file name, size and dimensions. It lists files only, never names.
// Uses `sharp` (already a devDependency).

import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MAX_SIDE = 600;
const QUALITY = 78;
const INPUT_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".tif", ".tiff"]);

/** "Jane Doe (2).JPG" -> "jane-doe-2" */
export function slugStem(fileName) {
  const stem = basename(fileName, extname(fileName));
  return (
    stem
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "photo"
  );
}

async function main() {
  const [src, out = join(ROOT, "public/people")] = process.argv.slice(2);
  if (!src) {
    console.error("Usage: node scripts/compress-photos.mjs <source-folder> [output-folder]");
    process.exit(1);
  }
  const srcDir = resolve(src);
  const outDir = resolve(out);
  mkdirSync(outDir, { recursive: true });

  const files = readdirSync(srcDir)
    .filter((f) => INPUT_EXT.has(extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b));
  if (files.length === 0) {
    console.error(`No images found in ${srcDir}`);
    process.exit(1);
  }

  const used = new Set();
  const rows = [];
  for (const file of files) {
    let name = slugStem(file);
    for (let n = 2; used.has(name); n++) name = `${slugStem(file)}-${n}`;
    used.add(name);

    const target = join(outDir, `${name}.webp`);
    const info = await sharp(join(srcDir, file))
      .rotate()
      .resize({ width: MAX_SIDE, height: MAX_SIDE, fit: "inside", withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(target);
    rows.push({
      file: `${name}.webp`,
      bytes: statSync(target).size,
      w: info.width,
      h: info.height,
    });
  }

  const total = rows.reduce((sum, r) => sum + r.bytes, 0);
  const kb = (b) => (b / 1024).toFixed(1);
  const md = [
    "# People photos",
    "",
    `Generated by \`node scripts/compress-photos.mjs\`. Max ${MAX_SIDE}px long side, WebP quality ${QUALITY}.`,
    "Files are listed by name only; this file does not say who is in which photo.",
    "",
    "| File | Size (KB) | Dimensions |",
    "| --- | ---: | --- |",
    ...rows.map((r) => `| ${r.file} | ${kb(r.bytes)} | ${r.w}×${r.h} |`),
    "",
    `Total: ${rows.length} files, ${kb(total)} KB.`,
    "",
  ].join("\n");
  mkdirSync(join(ROOT, "data"), { recursive: true });
  writeFileSync(join(ROOT, "data/people-photos.md"), md);

  console.log(`compress-photos: ${rows.length} files, ${kb(total)} KB total`);
  const biggest = rows.reduce((a, b) => (b.bytes > a.bytes ? b : a));
  console.log(`  largest: ${biggest.file} ${kb(biggest.bytes)} KB`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`compress-photos failed: ${err.message}`);
    process.exit(1);
  });
}
